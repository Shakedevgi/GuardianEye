"""
build_mixed_dataset.py - Phase 3 round 3: build the combined-training file
list for the "mixed" training experiment (see the task/PR that produced
this: docs/phase-3-step0-findings.md, "Round 1 fine-tune" + round 2's
regression on small_swallowable recall).

Round 1 (our 92 frames only) underfit from too little visual diversity.
Round 2 (sequential: public sharp_object-only data, THEN our frames) fixed
sharp_object recall but wrecked small_swallowable recall - stage 1 trained
95 epochs where every box in every image was class 0, and 54 class-1 boxes
in a 30-epoch stage 2 could not undo that.

This script does not train anything. It only produces one file:
`cv/datasets/phase3_v4_mixed/train.txt`, an Ultralytics image-list file that
mixes BOTH data sources into every epoch of a SINGLE training run, so class
1 (small_swallowable) is supervised throughout instead of being absent for
an entire first stage.

## The oversample knob

Raw ratio: 1,078 public images (class 0 only) vs. 79 of our own training
frames (both classes, after the existing images/train split - see
cv/prepare_dataset.py) = ~13.6:1 against us. Left alone, our frames -
and every small_swallowable box - would appear in roughly 1 batch out of 14
under random shuffling; round 2 already showed what "our class barely seen"
does.

REPEAT_FACTOR below controls how many times each of our 79 train frames is
duplicated as a LINE in train.txt (never a copy of the image bytes - see
module docstring further down). This is the single knob this experiment
turns; change it here or via --repeat-factor and rerun.

Chosen default: 14. 79 * 14 = 1,106, which lands our frames at
near-parity with the 1,078 public images (1,106 vs 1,078) rather than at
proportional-to-nothing. This is a deliberate choice, not a measured
optimum - nobody has swept this value. If the eval below still shows
small_swallowable starved relative to sharp_object, raising this number is
the first thing to try before touching anything else.

## What is NOT duplicated

- Image bytes: train.txt lines are plain paths; Ultralytics reads whichever
  file the line points to every time it is listed, so N duplicate lines
  cost N x (one extra path string), not N x (one extra JPEG on disk).
- The public data: used once each, no repeats - it exists for shape/colour/
  background diversity, and repeating it would not add diversity, only
  training time.
- Validation: intentionally NOT built by this script. Val stays
  cv/datasets/phase3_v1/images/val (13 of our own office frames) exactly as
  round 1/2 used it - the task requires validation to resemble deployment,
  and public knife/scissors photos (outdoor, studio, no floor-level
  context - see data/openimages_public/README.md's "Domain gap" section)
  do not.

Usage:
    python cv/build_mixed_dataset.py
    python cv/build_mixed_dataset.py --repeat-factor 20
"""

import argparse
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

PUBLIC_DIR = REPO_ROOT / "data" / "openimages_public"
OURS_DATASET_DIR = REPO_ROOT / "cv" / "datasets" / "phase3_v1"

OUTPUT_DIR = REPO_ROOT / "cv" / "datasets" / "phase3_v4_mixed"

DEFAULT_REPEAT_FACTOR = 14

CLASS_NAMES = ["sharp_object", "small_swallowable"]


def load_public_image_paths() -> list:
    """All 1,078 public images (both the stage-1 train.txt and val.txt
    splits from round 2 - that split had no purpose in this run, since
    validation here is entirely ours; using every public image for training
    is strictly more diversity for the same knob).
    """
    paths = []
    for list_name in ("train.txt", "val.txt"):
        list_path = PUBLIC_DIR / list_name
        paths.extend(Path(line) for line in list_path.read_text().splitlines() if line.strip())
    return paths


def load_our_train_image_paths() -> list:
    """The 79 frames already split into images/train by
    cv/prepare_dataset.py - the existing leak-free-by-duplicate-group split,
    unchanged. Resolved to absolute paths (the directory uses symlinks; the
    resolved path is what actually gets read).
    """
    return sorted((OURS_DATASET_DIR / "images" / "train").glob("*.jpg"))


def write_data_yaml(output_dir: Path) -> Path:
    names_block = "\n".join(f"  {i}: {name}" for i, name in enumerate(CLASS_NAMES))
    content = f"""\
# Auto-generated by cv/build_mixed_dataset.py - rewritten on every run, safe
# to regenerate, do not hand-edit.
#
# train: mixed list (public sharp_object-only images + our oversampled
#   office frames, both classes) - see train.txt and this script's docstring
#   for the repeat factor used.
# val: OUR frames only (cv/datasets/phase3_v1/images/val), unchanged from
#   rounds 1-2 - validation must resemble deployment, public data does not.

path: {output_dir.resolve()}
train: train.txt
val: {(OURS_DATASET_DIR / "images" / "val").resolve()}

names:
{names_block}
"""
    data_yaml = output_dir / "data.yaml"
    data_yaml.write_text(content)
    return data_yaml


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build the combined public+ours train.txt for the "
        "Phase 3 round 3 'mixed' training run."
    )
    parser.add_argument("--repeat-factor", type=int, default=DEFAULT_REPEAT_FACTOR,
                         help=f"How many times each of our train frames is "
                         f"duplicated as a train.txt LINE (not an image copy). "
                         f"Default {DEFAULT_REPEAT_FACTOR}.")
    parser.add_argument("--output-dir", type=str, default=str(OUTPUT_DIR))
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    public_paths = load_public_image_paths()
    our_paths = load_our_train_image_paths()
    if not our_paths:
        raise SystemExit(
            f"No images found under {OURS_DATASET_DIR / 'images' / 'train'} - "
            "run cv/prepare_dataset.py first."
        )

    repeated_our_paths = our_paths * args.repeat_factor

    all_lines = [str(p.resolve()) for p in public_paths] + \
                [str(p.resolve()) for p in repeated_our_paths]

    train_txt = output_dir / "train.txt"
    train_txt.write_text("\n".join(all_lines) + "\n")

    data_yaml = write_data_yaml(output_dir)

    total = len(all_lines)
    our_share = len(repeated_our_paths) / total if total else 0.0
    print(f"Public images: {len(public_paths)}")
    print(f"Our train frames: {len(our_paths)} x repeat-factor {args.repeat_factor} "
          f"= {len(repeated_our_paths)} line(s)")
    print(f"Combined train.txt: {total} line(s) "
          f"({our_share:.1%} ours by line count)")
    print(f"Val: {OURS_DATASET_DIR / 'images' / 'val'} (unchanged, ours only)")
    print(f"Wrote: {train_txt}")
    print(f"Wrote: {data_yaml}")


if __name__ == "__main__":
    main()
